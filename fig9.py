import numpy as np, matplotlib; matplotlib.use('Agg')
import matplotlib.pyplot as plt
plt.rcParams.update({'font.size':9,'font.family':'DejaVu Sans','axes.spines.top':False,
 'axes.spines.right':False,'figure.dpi':300,'savefig.bbox':'tight','savefig.pad_inches':.02})
n =np.array([0,1,2,3,5,10,25,50,100])
r =np.array([.6094,.8485,.9432,.9468,.9905,.9924,.9944,.9946,.9958])
sd=np.array([.0380,.1818,.1169,.1147,.0054,.0045,.0031,.0024,.0026])
x=np.where(n==0,0.4,n.astype(float))
fig,ax=plt.subplots(figsize=(4.6,3.0))
ax.fill_between(x,r-sd,r+sd,color='#4C72B0',alpha=.18,lw=0)
ax.plot(x,r,'-o',color='#4C72B0',ms=4,lw=1.4)
ax.axhline(.6094,color='#C44E52',ls='--',lw=1)
ax.text(1.1,.628,'no samples from target client (0.609)',fontsize=7,color='#C44E52')
ax.axvline(5,color='.5',ls=':',lw=.9)
ax.text(5.6,.70,'σ collapses at n = 5',fontsize=7,color='.35',rotation=90,va='bottom')
ax.set_xscale('symlog',linthresh=1); ax.set_xticks([0.4,1,2,5,10,25,100])
ax.set_xticklabels(['0','1','2','5','10','25','100'])
ax.set_xlabel('benign flows from the held-out client added to training')
ax.set_ylabel('ROC-AUC'); ax.set_ylim(.55,1.02)
fig.savefig('figs/fig9_threshold.pdf'); fig.savefig('figs/fig9_threshold.png')
print('ok')
